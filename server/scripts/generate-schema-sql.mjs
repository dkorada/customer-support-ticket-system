// Bundles the Prisma migrations into a TypeScript module so a fresh SQLite
// database can be created at runtime (Netlify Functions, tests) without the
// Prisma CLI. Run automatically by `npm run build`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../prisma/migrations/', import.meta.url).pathname;
const sql = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .map((name) => readFileSync(join(dir, name, 'migration.sql'), 'utf8'))
  .join('\n');

const statements = sql
  .split('\n')
  .filter((line) => !line.trim().startsWith('--'))
  .join('\n')
  .split(';')
  .map((s) => s.trim())
  .filter(Boolean);

const out = new URL('../src/generated/schema-sql.ts', import.meta.url).pathname;
writeFileSync(
  out,
  `// Generated by scripts/generate-schema-sql.mjs from prisma/migrations. Do not edit.\nexport const SCHEMA_STATEMENTS: string[] = ${JSON.stringify(statements, null, 2)};\n`,
);
console.log(`Wrote ${statements.length} schema statements to src/generated/schema-sql.ts`);
